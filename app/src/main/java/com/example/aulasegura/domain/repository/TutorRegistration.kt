package com.example.aulasegura.domain.repository

import com.example.aulasegura.domain.model.AppUser

/** What the family registration form collects. */
data class TutorRegistrationInput(
    val fullName: String,
    val email: String,
    val phone: String,
    val password: String,
    val code: String,
)

/** Typed outcome so the screen can explain exactly why a registration failed. */
sealed interface TutorRegistrationResult {

    data class Success(val user: AppUser) : TutorRegistrationResult

    /** Bad format or no such document. */
    data object InvalidCode : TutorRegistrationResult

    /** Another family already claimed it. */
    data object CodeAlreadyUsed : TutorRegistrationResult

    /** The directivo generated it too long ago. */
    data object ExpiredCode : TutorRegistrationResult

    data object EmailInUse : TutorRegistrationResult

    data object WeakPassword : TutorRegistrationResult

    data object NetworkError : TutorRegistrationResult

    /** Firestore refused the batch, usually because the rules are not published yet. */
    data object Rejected : TutorRegistrationResult

    data object Failed : TutorRegistrationResult
}

/**
 * Codes are six uppercase alphanumeric characters. Typing the mockup's
 * `ALU-2024-9821` is accepted by trimming separators, but the document that
 * exists in Firestore is the six-character one generated by the directivo.
 */
fun normalizeStudentCode(raw: String): String =
    raw.trim().uppercase().replace(Regex("[\\s-]"), "")

fun isValidStudentCode(code: String): Boolean =
    code.length == STUDENT_CODE_LENGTH && code.all { it.isLetterOrDigit() }

private const val STUDENT_CODE_LENGTH = 6

/** `null` means the form is ready to submit. */
fun registrationError(input: TutorRegistrationInput): String? = when {
    input.fullName.isBlank() -> "Escribe tu nombre completo."
    !input.email.contains("@") || !input.email.contains(".") ->
        "Escribe un correo electrónico válido."
    input.password.length < 8 -> "La contraseña debe tener al menos 8 caracteres."
    !isValidStudentCode(normalizeStudentCode(input.code)) ->
        "Escribe el código de 6 caracteres que te dio la escuela."
    else -> null
}

fun registrationMessage(result: TutorRegistrationResult): String = when (result) {
    is TutorRegistrationResult.Success -> "Cuenta creada."
    TutorRegistrationResult.InvalidCode ->
        "Ese código no existe. Revisa los 6 caracteres que te dio la escuela."
    TutorRegistrationResult.CodeAlreadyUsed ->
        "Ese código ya fue usado. Pide uno nuevo a la escuela."
    TutorRegistrationResult.ExpiredCode ->
        "Ese código venció. Pide uno nuevo a la escuela."
    TutorRegistrationResult.EmailInUse ->
        "Ya existe una cuenta con ese correo. Inicia sesión."
    TutorRegistrationResult.WeakPassword ->
        "La contraseña es demasiado débil."
    TutorRegistrationResult.NetworkError ->
        "Sin conexión. Revisa tu red e inténtalo de nuevo."
    TutorRegistrationResult.Rejected ->
        "La escuela no pudo crear la cuenta. Contacta a la administración."
    TutorRegistrationResult.Failed ->
        "No pudimos crear la cuenta. Inténtalo de nuevo."
}
